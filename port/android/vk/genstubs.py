# Generates ttt2vk_stubs.h: python3 genstubs.py <dxvk-native>/include/native/directx ID3D11DeviceContext1 ID3D11Device1 ... (see the header list)
import re, sys, glob
D=sys.argv[1].rstrip("/")+"/" if len(sys.argv) > 1 and sys.argv[1].endswith("directx") else "include/native/directx/"
files=['d3d11.h','d3d11_1.h','dxgi.h','dxgi1_2.h']
ifaces={}
for fn in files:
    s=open(D+fn).read()
    for m in re.finditer(r'\n(\w+) : public (\w+)\s*\n\{(.*?)\n\};', s, re.S):
        name, base, body = m.group(1), m.group(2), m.group(3)
        if name in ifaces: continue
        meths=[]
        for mm in re.finditer(r'virtual\s+(.*?)\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*(const)?\s*=\s*0\s*;', body, re.S):
            ret=' '.join(mm.group(1).split()); nm=mm.group(2); params=' '.join(mm.group(3).split()); const=mm.group(4) or ''
            meths.append((ret,nm,params,const))
        ifaces[name]=(base,meths)
def chain(n):
    out=[]
    while n in ifaces:
        base,meths=ifaces[n]; out=meths+out; n=base
    return out
want=[a for a in sys.argv[1:] if not a.endswith("directx")]
print('// Generated by genstubs.py from the DXVK-native interface headers: every method a default (E_NOTIMPL / nothing).')
print('#pragma once')
for w in want:
    ms=chain(w); seen=set()
    print(f'template <class T> struct Stub_{w} : T {{')
    for ret,nm,params,const in ms:
        key=(nm,params)
        if key in seen: continue
        seen.add(key)
        if ret=='void': body='{}'
        elif ret=='HRESULT': body='{ return E_NOTIMPL; }'
        else: body='{ return {}; }'
        print(f'    {ret} STDMETHODCALLTYPE {nm}({params}) {const} override {body}')
    print('};')
